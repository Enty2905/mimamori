let saved: string | null = null;
try {
  saved = Storage.getItemSync("mimamori.language");
} catch {
  /* Native storage can be unavailable in previews. */
}
const language =
  saved === "ja" || saved === "vi"
    ? saved
    : getLocales()[0]?.languageCode === "ja"
      ? "ja"
      : "vi";
void i18n
  .use(initReactI18next)
  .init({
    resources: { vi: { translation: vi }, ja: { translation: ja } },
    lng: language,
    fallbackLng: "vi",
    interpolation: { escapeValue: false },
    initAsync: false,
  });
export async function changeLanguage(value: "ja" | "vi") {
  await i18n.changeLanguage(value);
  await Storage.setItem("mimamori.language", value);
}
export default i18n;
